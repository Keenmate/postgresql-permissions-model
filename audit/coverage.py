"""Cross-reference database functions against the test suites.

Reads db-objects.json, scans tests/ for calls to each function
(schema-qualified, e.g. `auth.has_permission(`), and writes
audit/coverage.md listing functions grouped by schema with the number of
test files that reference them. Functions with zero references are listed
first - they are the cheapest place to start looking for missing tests.

Usage: python audit/coverage.py
"""
import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS = ("auth", "public", "internal", "unsecure", "helpers", "triggers")

objects = json.loads((ROOT / "db-objects.json").read_text(encoding="utf-8"))
functions = sorted(
    {(o["schema"], o["object_name"], o["last_update_file"], o["last_update_line"])
     for o in objects if o["object_type"] == "function" and o["schema"] in SCHEMAS}
)

test_files = {
    p.relative_to(ROOT / "tests").as_posix(): p.read_text(encoding="utf-8", errors="replace").lower()
    for p in (ROOT / "tests").rglob("*.sql")
}

hits = {}
for schema, name, *_ in functions:
    pattern = re.compile(rf"\b{schema}\.{re.escape(name.lower())}\s*\(")
    hits[(schema, name)] = sorted(f for f, text in test_files.items() if pattern.search(text))

# Trigger functions are never called directly; mark them so they are not mistaken for gaps.
untested = [f for f in functions if not hits[f[:2]] and f[0] != "triggers"]

by_schema = defaultdict(list)
for f in functions:
    by_schema[f[0]].append(f)

out = ["# Test coverage by function", "",
       "Generated by `python audit/coverage.py`. A function counts as covered when any file under "
       "`tests/` calls it schema-qualified. This says nothing about *how well* it is tested - "
       "it only finds functions no test touches at all. Trigger functions are exercised "
       "indirectly and are listed but not counted as gaps.", "",
       f"- Functions scanned: {len(functions)}",
       f"- Never referenced by a test (excluding triggers): {len(untested)}", "",
       "## Never referenced by any test", "",
       "| Function | Defined at |", "|---|---|"]
out += [f"| `{s}.{n}` | `{file}:{line}` |" for s, n, file, line in untested]

for schema in SCHEMAS:
    if schema not in by_schema:
        continue
    out += ["", f"## {schema}", "", "| Function | Test files | Referenced in |", "|---|---|---|"]
    for s, n, *_ in by_schema[schema]:
        files = hits[(s, n)]
        suites = sorted({f.split("/")[0] for f in files})
        out.append(f"| `{s}.{n}` | {len(files)} | {', '.join(suites)} |")

(ROOT / "audit" / "coverage.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(functions)} functions, {len(untested)} untested -> audit/coverage.md")
